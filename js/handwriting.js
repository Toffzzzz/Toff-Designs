/* =====================================================================
   Handwriting: lays out text in a single-line font as pen strokes.
   Used by script.js (the site) and fonts-preview.html.

   Font data comes from paths/fonts/<id>.js (generated by
   tools/build-fonts.mjs): centre lines only, so each stroke is drawn once,
   never a letter outline.

   Drawing order for each word: every letter's strokes left to right in the
   font's pen order, then the word's i/j dots and t crosses, left to right.
   ===================================================================== */
(function () {
  const loading = {};

  /** Loads paths/fonts/<id>.js once; resolves with the font data. */
  function loadFont(id, base = '') {
    const fonts = (window.TOFF_FONTS = window.TOFF_FONTS || {});
    if (fonts[id]) return Promise.resolve(fonts[id]);
    if (!loading[id]) {
      loading[id] = new Promise((resolve, reject) => {
        const s = document.createElement('script');
        s.src = `${base}paths/fonts/${id}.js`;
        s.onload = () => (fonts[id] ? resolve(fonts[id]) : reject(new Error(`Font ${id} is empty`)));
        s.onerror = () => reject(new Error(`Font ${id} not found in paths/fonts/`));
        document.head.append(s);
      });
    }
    return loading[id];
  }

  // Every number pair in these paths is a point (only M, L, C, Q are used)
  function transformPath(d, ox, oy, k) {
    const out = [];
    const re = /([MLCQ])|(-?\d*\.?\d+(?:e[-+]?\d+)?)/g;
    let m;
    let pending = null;
    const pts = [];
    while ((m = re.exec(d))) {
      if (m[1]) {
        out.push(m[1]);
        continue;
      }
      const v = parseFloat(m[2]);
      if (pending === null) {
        pending = v;
      } else {
        const x = ox + pending * k;
        const y = oy + v * k;
        pts.push([x, y]);
        out.push(`${x.toFixed(2)} ${y.toFixed(2)}`);
        pending = null;
      }
    }
    return { d: out.join(' ').replace(/([MLCQ]) /g, '$1'), pts };
  }

  function direction(a, b) {
    const dx = b[0] - a[0];
    const dy = b[1] - a[1];
    const len = Math.hypot(dx, dy) || 1;
    return [dx / len, dy / len];
  }

  // A direction from the first/last few points, ignoring tiny wiggles
  function endDirection(pts, fromStart) {
    if (pts.length < 2) return [1, 0];
    const p = fromStart ? pts : [...pts].reverse();
    const a = p[0];
    let b = p[1];
    for (let i = 1; i < p.length; i++) {
      b = p[i];
      if (Math.hypot(b[0] - a[0], b[1] - a[1]) > 6) break;
    }
    const dir = direction(a, b);
    return fromStart ? dir : [-dir[0], -dir[1]];
  }

  /** Width (px) and ink extents of one line of text, without drawing it. */
  function measureLine(font, text, em, letterSpacing = 0) {
    const k = em / (font.unitsPerEm || 1000);
    let x = 0;
    let minX = Infinity;
    let maxX = -Infinity;
    let minY = Infinity;
    let maxY = -Infinity;
    for (const ch of text) {
      const g = font.glyphs[ch] || font.glyphs[' '] || { a: 500, s: [] };
      for (const s of g.s) {
        const { pts } = transformPath(s.d, x, 0, k);
        for (const [px, py] of pts) {
          if (px < minX) minX = px;
          if (px > maxX) maxX = px;
          if (py < minY) minY = py;
          if (py > maxY) maxY = py;
        }
      }
      x += g.a * k + letterSpacing * em;
    }
    if (minX === Infinity) minX = maxX = minY = maxY = 0;
    return { advance: x - letterSpacing * em, minX, maxX, minY, maxY, width: maxX - minX };
  }

  /** Splits text into lines no wider than maxWidth (px), at spaces. */
  function wrap(font, text, em, letterSpacing, maxWidth) {
    if (!maxWidth) return [text];
    const words = text.split(' ');
    const lines = [];
    let line = '';
    for (const w of words) {
      const next = line ? `${line} ${w}` : w;
      if (line && measureLine(font, next, em, letterSpacing).width > maxWidth) {
        lines.push(line);
        line = w;
      } else {
        line = next;
      }
    }
    if (line) lines.push(line);
    return lines;
  }

  /**
   * Lays out text as pen strokes.
   * options: { em (px), letterSpacing (em), x, y (first baseline), lines (array
   * of strings, optional), lineHeight (em) , align: 'left'|'center' , width }
   * Returns { strokes, bbox, start, startDir, end, endDir }.
   * x is where the ink starts (the left edge of the first letter's ink).
   */
  function layout(font, text, options) {
    const { em, letterSpacing = 0, x = 0, y = 0, lineHeight = 1.25 } = options;
    const k = em / (font.unitsPerEm || 1000);
    const lines = options.lines || [text];
    const strokes = [];
    let lastMain = null;

    lines.forEach((lineText, li) => {
      const m = measureLine(font, lineText, em, letterSpacing);
      let ox = x - m.minX;
      if (options.align === 'center' && options.width) ox = x + (options.width - m.width) / 2 - m.minX;
      const oy = y + li * lineHeight * em;
      let pending = []; // this word's dots and crosses
      let wordIndex = 0;
      const flushWord = () => {
        pending.sort((a, b) => a.pts[0][0] - b.pts[0][0]);
        for (const s of pending) strokes.push(s);
        pending = [];
      };
      [...lineText].forEach((ch, ci) => {
        const g = font.glyphs[ch] || { a: 500, s: [] };
        if (ch === ' ') {
          flushWord();
          wordIndex++;
        }
        g.s.forEach((s, si) => {
          const t = transformPath(s.d, ox, oy, k);
          const stroke = {
            d: t.d,
            pts: t.pts,
            kind: s.t || 'main',
            char: ch,
            line: li,
            word: wordIndex,
            key: `${li}-${ci}-${si}`,
            start: t.pts[0],
            end: t.pts[t.pts.length - 1],
            startDir: endDirection(t.pts, true),
            endDir: endDirection(t.pts, false),
            newWord: false,
          };
          if (s.t) pending.push(stroke);
          else {
            strokes.push(stroke);
            lastMain = stroke;
          }
        });
        ox += g.a * k + letterSpacing * em;
      });
      flushWord();
    });

    // Mark the first stroke of each word (for the pause between words)
    let prevWord = null;
    for (const s of strokes) {
      const id = `${s.line}:${s.word}`;
      s.newWord = prevWord !== null && id !== prevWord;
      prevWord = id;
    }

    let minX = Infinity;
    let maxX = -Infinity;
    let minY = Infinity;
    let maxY = -Infinity;
    for (const s of strokes) {
      for (const [px, py] of s.pts) {
        if (px < minX) minX = px;
        if (px > maxX) maxX = px;
        if (py < minY) minY = py;
        if (py > maxY) maxY = py;
      }
    }

    // The joining line leaves from the end of the last letter's last stroke.
    // If the text ends with punctuation drawn last (the dot of "?"), that
    // stroke is the end.
    const last = strokes[strokes.length - 1];
    const exit = last && last.kind === 'main' ? last : lastMain || last;
    const first = strokes[0];
    return {
      strokes,
      bbox: { x: minX, y: minY, width: maxX - minX, height: maxY - minY, minX, maxX, minY, maxY },
      start: first ? first.start : [x, y],
      startDir: first ? first.startDir : [1, 0],
      end: exit ? exit.end : [x, y],
      endDir: exit ? exit.endDir : [1, 0],
    };
  }

  /** Approximate pen travel (px) of a stroke, from its points. */
  function strokeLength(s) {
    let len = 0;
    for (let i = 1; i < s.pts.length; i++) {
      len += Math.hypot(s.pts[i][0] - s.pts[i - 1][0], s.pts[i][1] - s.pts[i - 1][1]);
    }
    return len;
  }

  window.TOFF_HW = { loadFont, layout, measureLine, wrap, strokeLength };
})();
